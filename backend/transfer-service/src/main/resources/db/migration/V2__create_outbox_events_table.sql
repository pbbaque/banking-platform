CREATE TABLE OUTBOX_EVENTS (
    ID RAW(16) NOT NULL,
    AGGREGATE_ID RAW(16) NOT NULL,
    EVENT_TYPE VARCHAR2(100 CHAR) NOT NULL,
    PAYLOAD CLOB NOT NULL,
    STATUS VARCHAR2(20 CHAR) NOT NULL,
    ATTEMPTS NUMBER(10) DEFAULT 0 NOT NULL,
    LAST_ERROR VARCHAR2(1000 CHAR),
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    AVAILABLE_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    PUBLISHED_AT TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_OUTBOX_EVENTS PRIMARY KEY (ID),
    CONSTRAINT CK_OUTBOX_EVENTS_STATUS CHECK (STATUS IN ('PENDING', 'PUBLISHED')),
    CONSTRAINT CK_OUTBOX_EVENTS_ATTEMPTS CHECK (ATTEMPTS >= 0)
);
CREATE INDEX IDX_OUTBOX_EVENTS_PENDING ON OUTBOX_EVENTS (STATUS, AVAILABLE_AT);
CREATE INDEX IDX_OUTBOX_EVENTS_AGGREGATE_ID ON OUTBOX_EVENTS (AGGREGATE_ID);
CREATE INDEX IDX_OUTBOX_EVENTS_CREATED_AT ON OUTBOX_EVENTS (CREATED_AT);