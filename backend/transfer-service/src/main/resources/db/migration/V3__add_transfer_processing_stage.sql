ALTER TABLE TRANSFERS
ADD PROCESSING_STAGE VARCHAR2(30 CHAR);
UPDATE TRANSFERS
SET PROCESSING_STAGE = CASE
        WHEN STATUS IN ('COMPLETED', 'FAILED') THEN 'TERMINAL'
        WHEN STATUS = 'PENDING' THEN 'RECOVERY_REQUIRED'
    END;
ALTER TABLE TRANSFERS
MODIFY PROCESSING_STAGE NOT NULL;
ALTER TABLE TRANSFERS
ADD CONSTRAINT CK_TRANSFERS_PROCESSING_STAGE CHECK (
        PROCESSING_STAGE IN (
            'DEBIT_PENDING',
            'CREDIT_PENDING',
            'COMPENSATION_PENDING',
            'TERMINAL',
            'RECOVERY_REQUIRED'
        )
    );