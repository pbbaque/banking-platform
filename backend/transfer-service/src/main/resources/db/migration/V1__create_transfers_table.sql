CREATE TABLE TRANSFERS (
    ID RAW(16) NOT NULL,
    SOURCE_ACCOUNT_ID RAW(16) NOT NULL,
    DESTINATION_ACCOUNT_ID RAW(16) NOT NULL,
    AMOUNT NUMBER(19, 4) NOT NULL,
    CURRENCY VARCHAR2(3 CHAR) NOT NULL,
    STATUS VARCHAR2(30 CHAR) NOT NULL,
    IDEMPOTENCY_KEY VARCHAR2(100 CHAR) NOT NULL,
    FAILURE_REASON VARCHAR2(500 CHAR),
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    COMPLETED_AT TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_TRANSFERS PRIMARY KEY (ID),
    CONSTRAINT UK_TRANSFERS_IDEMPOTENCY_KEY UNIQUE (IDEMPOTENCY_KEY),
    CONSTRAINT CK_TRANSFERS_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_TRANSFERS_CURRENCY CHECK (CURRENCY IN ('EUR')),
    CONSTRAINT CK_TRANSFERS_STATUS CHECK (STATUS IN ('PENDING', 'COMPLETED', 'FAILED')),
    CONSTRAINT CK_TRANSFERS_ACCOUNTS CHECK (SOURCE_ACCOUNT_ID <> DESTINATION_ACCOUNT_ID)
);
CREATE INDEX IDX_TRANSFERS_SOURCE_ACCOUNT_ID ON TRANSFERS (SOURCE_ACCOUNT_ID);
CREATE INDEX IDX_TRANSFERS_DESTINATION_ACCOUNT_ID ON TRANSFERS (DESTINATION_ACCOUNT_ID);
CREATE INDEX IDX_TRANSFERS_STATUS ON TRANSFERS (STATUS);