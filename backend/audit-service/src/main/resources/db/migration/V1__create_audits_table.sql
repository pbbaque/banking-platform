CREATE TABLE AUDIT_EVENTS (
    ID RAW(16) NOT NULL,
    EVENT_TYPE VARCHAR2(100 CHAR) NOT NULL,
    AGGREGATE_TYPE VARCHAR2(100 CHAR) NOT NULL,
    AGGREGATE_ID VARCHAR2(100 CHAR) NOT NULL,
    ACTOR_ID RAW(16),
    OUTCOME VARCHAR2(20 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(500 CHAR),
    METADATA CLOB,
    OCCURRED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_AUDIT_EVENTS PRIMARY KEY (ID),
    CONSTRAINT CK_AUDIT_EVENTS_OUTCOME CHECK (OUTCOME IN ('SUCCESS', 'FAILURE'))
);
CREATE INDEX IDX_AUDIT_EVENTS_AGGREGATE ON AUDIT_EVENTS (AGGREGATE_TYPE, AGGREGATE_ID);
CREATE INDEX IDX_AUDIT_EVENTS_EVENT_TYPE ON AUDIT_EVENTS (EVENT_TYPE);
CREATE INDEX IDX_AUDIT_EVENTS_ACTOR_ID ON AUDIT_EVENTS (ACTOR_ID);
CREATE INDEX IDX_AUDIT_EVENTS_OCCURRED_AT ON AUDIT_EVENTS (OCCURRED_AT);