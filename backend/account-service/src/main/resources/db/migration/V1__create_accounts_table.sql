CREATE TABLE ACCOUNTS (
    ID RAW(16) NOT NULL,
    CUSTOMER_ID RAW(16) NOT NULL,
    IBAN VARCHAR2(34 CHAR) NOT NULL,
    ACCOUNT_TYPE VARCHAR2(30 CHAR) NOT NULL,
    CURRENCY VARCHAR2(3 CHAR) NOT NULL,
    BALANCE NUMBER(19, 4) DEFAULT 0 NOT NULL,
    STATUS VARCHAR2(30 CHAR) NOT NULL,
    VERSION NUMBER(19) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CLOSED_AT TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_ACCOUNTS PRIMARY KEY (ID),
    CONSTRAINT UK_ACCOUNTS_IBAN UNIQUE (IBAN),
    CONSTRAINT CK_ACCOUNTS_TYPE CHECK (ACCOUNT_TYPE IN ('CHECKING', 'SAVINGS')),
    CONSTRAINT CK_ACCOUNTS_CURRENCY CHECK (CURRENCY IN ('EUR')),
    CONSTRAINT CK_ACCOUNTS_STATUS CHECK (STATUS IN ('ACTIVE', 'BLOCKED', 'CLOSED')),
    CONSTRAINT CK_ACCOUNTS_BALANCE CHECK (BALANCE >= 0)
);
CREATE INDEX IDX_ACCOUNTS_CUSTOMER_ID ON ACCOUNTS (CUSTOMER_ID);
CREATE INDEX IDX_ACCOUNTS_STATUS ON ACCOUNTS (STATUS);