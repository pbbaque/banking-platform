CREATE TABLE ACCOUNT_OPERATIONS (
    ID RAW(16) NOT NULL,
    ACCOUNT_ID RAW(16) NOT NULL,
    OPERATION_TYPE VARCHAR2(20 CHAR) NOT NULL,
    AMOUNT NUMBER(19, 4) NOT NULL,
    RESULTING_BALANCE NUMBER(19, 4) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_ACCOUNT_OPERATIONS PRIMARY KEY (ID),
    CONSTRAINT FK_ACCOUNT_OPERATIONS_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNTS (ID),
    CONSTRAINT CK_ACCOUNT_OPERATIONS_TYPE CHECK (OPERATION_TYPE IN ('CREDIT', 'DEBIT')),
    CONSTRAINT CK_ACCOUNT_OPERATIONS_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_ACCOUNT_OPERATIONS_BALANCE CHECK (RESULTING_BALANCE >= 0)
);
CREATE INDEX IDX_ACCOUNT_OPERATIONS_ACCOUNT_ID ON ACCOUNT_OPERATIONS (ACCOUNT_ID);
CREATE INDEX IDX_ACCOUNT_OPERATIONS_CREATED_AT ON ACCOUNT_OPERATIONS (CREATED_AT);